function distanceBetween(a,b) {
  const rad=n=>n*Math.PI/180; const dLat=rad(b[0]-a[0]),dLon=rad(b[1]-a[1]);
  const h=Math.sin(dLat/2)**2+Math.cos(rad(a[0]))*Math.cos(rad(b[0]))*Math.sin(dLon/2)**2;
  return 6371*2*Math.asin(Math.sqrt(h));
}
function getCityProviders(city) {
  const all=trainingProviders.filter(p=>p.active!==false);
  if(city==='Other') return {items:all,message:'اخترت مدينة أخرى، هذه كل المعاهد المتوفرة',fallback:false};
  const exact=all.filter(p=>p.city===city);
  if(exact.length) return {items:exact,message:'',fallback:false};
  const known=all.filter(p=>cityPoints[p.city]);
  const ordered=[...known].sort((a,b)=>distanceBetween(cityPoints[city],cityPoints[a.city])-distanceBetween(cityPoints[city],cityPoints[b.city]));
  const nearestCity=ordered[0]?.city;
  return {items:ordered.filter(p=>p.city===nearestCity),message:'لا يوجد معهد مطابق في مدينتك حالياً، هذه أقرب المعاهد لك:',fallback:true};
}

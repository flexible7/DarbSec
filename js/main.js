let questions = [];

function getExperienceBand(stage, value) {
    if (stage === 'graduate') return value ? `graduate-${value}` : '';
    if (stage !== 'expert') return '';
    if (value === '10plus') return '10+';
    const years = Number(value || 0);
    if (years >= 1 && years <= 3) return '1-3';
    if (years >= 4 && years <= 6) return '4-6';
    if (years >= 7 && years <= 10) return '7-10';
    return '';
}

function selectQuestionBank(stage, experienceValue = '') {
    if (stage === 'student') return studentQuestions;
    if (stage === 'graduate') return graduateQuestions;
    if (stage === 'employee') return employeeQuestions;
    if (stage === 'expert') return buildExpertQuestions(getExperienceBand(stage, experienceValue));
    return studentQuestions;
}

function shuffleArray(array) {
    const clone = Array.isArray(array) ? [...array] : [];
    for (let i = clone.length - 1; i > 0; i--) {
        const j = Math.floor(Math.random() * (i + 1));
        [clone[i], clone[j]] = [clone[j], clone[i]];
    }
    return clone;
}

function cloneQuestionBank(bank) {
    return (Array.isArray(bank) ? bank : []).map(question => ({
        q: question.q,
        hint: question.hint || '',
        a: (Array.isArray(question.a) ? question.a : []).map(answer => ({
            text: answer.text,
            scores: { ...(answer.scores || {}) }
        }))
    }));
}

function prepareQuizQuestions(bank) {
    const prepared = cloneQuestionBank(bank).map(question => ({
        ...question,
        a: shuffleArray(question.a)
    }));
    return shuffleArray(prepared);
}



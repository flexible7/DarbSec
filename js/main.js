function resetQuizScore() {
    quizScore = Object.fromEntries(advisorPaths.map(path => [path, 0]));
    quizAnswers = [];
}



function getScoreEntries() {
    const maxScore = Math.max(1, ...Object.values(quizScore).map(v => Number(v) || 0));
    return advisorPaths
        .map(path => ({ path, score: Number(quizScore[path]) || 0, percent: Math.round(((Number(quizScore[path]) || 0) / maxScore) * 100) }))
        .sort((a, b) => b.score - a.score);
}

function getWinningPath() {
    return getScoreEntries()[0]?.path || 'foundation';
}

function percentFor(path) {
    const entry = getScoreEntries().find(item => item.path === path);
    return entry ? entry.percent : 0;
}

function getPathCerts(pathKey, limit = 5) {
    const profile = pathProfiles[pathKey] || pathProfiles.foundation;
    if (typeof certData === 'undefined' || !certData) {
        return (profile.fallbackCerts || []).slice(0, limit).map((title, index) => ({
            id: `fallback_${index}`,
            badge: title,
            display_title: title,
            org: 'دليل DarbSec',
            level: index < 2 ? 'مبتدئ' : 'متوسط',
            duration: 'حسب مستواك',
            recommended_for: 'خيار مناسب كبداية أو خطوة لاحقة لهذا المسار.',
            priority: index + 1
        }));
    }

    return Object.entries(certData)
        .filter(([, cert]) => cert && (cert.cat === pathKey || (Array.isArray(cert.paths) && cert.paths.includes(pathKey))))
        .map(([id, cert]) => ({ id, ...cert, priority: Number(cert.priority) || 999 }))
        .sort((a, b) => a.priority - b.priority)
        .slice(0, limit);
}



function getTrackInfo(path) {
    const meta = (typeof trackMeta !== "undefined" && trackMeta[path]) ? trackMeta[path] : defaultTrackMeta[path];
    const fallback = defaultTrackMeta[path] || defaultTrackMeta.foundation;
    return {
        title: meta.title || fallback.title,
        short: meta.short || fallback.short,
        icon: meta.icon || fallback.icon,
        color: meta.color || fallback.color,
        desc: meta.desc || fallback.desc
    };
}

